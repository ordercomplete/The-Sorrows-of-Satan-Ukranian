import re
from pathlib import Path

def normalize_archaic_to_modern(text: str) -> str:
    """
    Перетворює текст з архаїчних літер на сучасну російську орфографію.
    
    Правила:
    - ѣ → е (ят)
    - і → и (українська і, яка зустрічається в історичних текстах)
    - ъ на кінці слів → видаляється (ефированіє)
    - ъ перед приголосними на кінці слова → іноді зберігається як ь
    - ѫ → ю (юс)
    - ѧ → я (малюю юс)
    - ѳ → ф (фита)
    - ѵ → и (іжиця)
    """
    
    # Порядок важливий! Спочатку складніші комбінації
    
    # Юс: ѫ → ю, ѧ → я
    text = text.replace('ѫ', 'ю')
    text = text.replace('ѧ', 'я')
    
    # Фита: ѳ → ф
    text = text.replace('ѳ', 'ф')
    
    # Іжиця: ѵ → и
    text = text.replace('ѵ', 'и')
    
    # Ят: ѣ → е
    text = text.replace('ѣ', 'е')
    
    # Енд на кінці слів: слов[ъ] → слов
    # Але зберігаємо ъ як м'який знак в інших позиціях
    text = re.sub(r'ъ\b', '', text)
    
    return text

def fix_common_ocr_errors(text: str) -> str:
    """
    Виправляє поширені помилки OCR:
    - Переставлені слова
    - Зайві пробіли
    - Неправильні розриви рядків
    """
    
    # Видаляємо зайві пробіли
    text = re.sub(r' +', ' ', text)
    text = re.sub(r' \n', '\n', text)
    
    # Виправляємо розриви слів через дефіс в кінці рядка
    # Наприклад: "не встрѣтивъ-" → "не встрітив"
    text = re.sub(r'(\w)-\n(\w)', r'\1\2', text)
    
    return text

def modernize_text(text: str) -> str:
    """
    Повна модернізація тексту:
    1. Заміна архаїчних літер
    2. Виправлення помилок OCR
    """
    text = normalize_archaic_to_modern(text)
    text = fix_common_ocr_errors(text)
    return text

